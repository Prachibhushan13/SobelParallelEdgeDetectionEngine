#include "image_io.h"
#include <fstream>
#include <sstream>
#include <cmath>
#include <algorithm>
#include <cstring>

static void skip_comments(std::istream& is) {
    while (true) {
        // Skip whitespace
        while (isspace(is.peek())) {
            is.get();
        }
        // Check for comment
        if (is.peek() == '#') {
            std::string dummy;
            std::getline(is, dummy);
        } else {
            break;
        }
    }
}

bool load_pgm(const std::string& filepath, Image& image, std::string& error_msg) {
    std::ifstream file(filepath, std::ios::binary);
    if (!file.is_open()) {
        error_msg = "Could not open file: " + filepath;
        return false;
    }

    std::string magic;
    file >> magic;
    if (magic != "P5" && magic != "P2") {
        error_msg = "Invalid PGM header (expected P5 or P2, got " + magic + "): " + filepath;
        return false;
    }

    skip_comments(file);
    int width = 0, height = 0, maxval = 0;
    if (!(file >> width)) {
        error_msg = "Failed reading image width";
        return false;
    }

    skip_comments(file);
    if (!(file >> height)) {
        error_msg = "Failed reading image height";
        return false;
    }

    skip_comments(file);
    if (!(file >> maxval)) {
        error_msg = "Failed reading image maxval";
        return false;
    }

    if (width <= 0 || height <= 0) {
        error_msg = "Invalid image dimensions: " + std::to_string(width) + "x" + std::to_string(height);
        return false;
    }

    if (maxval <= 0 || maxval > 255) {
        error_msg = "Unsupported maxval (only <= 255 supported): " + std::to_string(maxval);
        return false;
    }

    // Skip the single whitespace character after maxval (usually \n)
    file.get();

    image = Image(width, height);

    if (magic == "P5") {
        // Binary format
        file.read(reinterpret_cast<char*>(image.data.data()), static_cast<std::streamsize>(width * height));
        if (file.gcount() != static_cast<std::streamsize>(width * height)) {
            error_msg = "Unexpected end of file while reading P5 binary data";
            return false;
        }
    } else {
        // P2 ASCII format
        for (int i = 0; i < width * height; ++i) {
            int val;
            if (!(file >> val)) {
                error_msg = "Unexpected end of file while reading P2 ASCII data";
                return false;
            }
            image.data[i] = static_cast<uint8_t>(std::clamp(val, 0, 255));
        }
    }

    return true;
}

bool save_pgm(const std::string& filepath, const Image& image, std::string& error_msg) {
    if (image.empty()) {
        error_msg = "Cannot save empty image";
        return false;
    }

    std::ofstream file(filepath, std::ios::binary);
    if (!file.is_open()) {
        error_msg = "Could not open file for writing: " + filepath;
        return false;
    }

    // Write standard P5 PGM binary header
    file << "P5\n";
    file << "# Generated by Sobel Edge Detection BCS702 Engine\n";
    file << image.width << " " << image.height << "\n";
    file << "255\n";

    file.write(reinterpret_cast<const char*>(image.data.data()), static_cast<std::streamsize>(image.data.size()));
    if (!file.good()) {
        error_msg = "Error occurred while writing image pixel buffer";
        return false;
    }

    return true;
}

ImageDiffResult compare_images(const Image& img1, const Image& img2, uint8_t tolerance) {
    ImageDiffResult res;
    if (img1.width != img2.width || img1.height != img2.height) {
        res.exact_match = false;
        return res;
    }

    res.total_pixels = img1.width * img1.height;
    double sum_abs_err = 0.0;
    double sum_sq_err = 0.0;
    uint8_t max_d = 0;
    int diff_count = 0;

    for (size_t i = 0; i < img1.data.size(); ++i) {
        int diff = std::abs(static_cast<int>(img1.data[i]) - static_cast<int>(img2.data[i]));
        if (diff > max_d) max_d = static_cast<uint8_t>(diff);
        if (diff > tolerance) diff_count++;
        sum_abs_err += diff;
        sum_sq_err += diff * diff;
    }

    res.max_difference = max_d;
    res.differing_pixels = diff_count;
    res.mean_absolute_error = sum_abs_err / res.total_pixels;
    res.mean_squared_error = sum_sq_err / res.total_pixels;
    res.exact_match = (diff_count == 0);

    return res;
}

Image create_gradient_ramp(int width, int height) {
    Image img(width, height);
    for (int y = 0; y < height; ++y) {
        for (int x = 0; x < width; ++x) {
            uint8_t val = static_cast<uint8_t>((x * 255) / (width > 1 ? width - 1 : 1));
            img.set(x, y, val);
        }
    }
    return img;
}

Image create_chessboard(int width, int height, int square_size) {
    Image img(width, height);
    if (square_size <= 0) square_size = 32;
    for (int y = 0; y < height; ++y) {
        int row_block = y / square_size;
        for (int x = 0; x < width; ++x) {
            int col_block = x / square_size;
            uint8_t val = ((row_block + col_block) % 2 == 0) ? 230 : 25;
            img.set(x, y, val);
        }
    }
    return img;
}

Image create_concentric_circles(int width, int height) {
    Image img(width, height);
    double cx = width / 2.0;
    double cy = height / 2.0;
    double max_r = std::hypot(cx, cy);

    for (int y = 0; y < height; ++y) {
        for (int x = 0; x < width; ++x) {
            double r = std::hypot(x - cx, y - cy);
            double freq = 20.0 * (r / (max_r > 0 ? max_r : 1.0));
            double wave = std::sin(freq * 3.141592653589793);
            uint8_t val = static_cast<uint8_t>(std::clamp((wave + 1.0) * 127.5, 0.0, 255.0));
            img.set(x, y, val);
        }
    }
    return img;
}

Image create_geometric_shapes(int width, int height) {
    Image img(width, height, 40); // Dark gray background

    // Center bright circle
    int cx = width / 2;
    int cy = height / 2;
    int radius = std::min(width, height) / 4;
    for (int y = 0; y < height; ++y) {
        for (int x = 0; x < width; ++x) {
            int dx = x - cx;
            int dy = y - cy;
            if (dx * dx + dy * dy <= radius * radius) {
                img.set(x, y, 220);
            }
        }
    }

    // Top-left rectangle
    int rx1 = width / 8, ry1 = height / 8;
    int rw = width / 4, rh = height / 5;
    for (int y = ry1; y < ry1 + rh && y < height; ++y) {
        for (int x = rx1; x < rx1 + rw && x < width; ++x) {
            img.set(x, y, 180);
        }
    }

    // Bottom-right diagonal triangle
    for (int y = height / 2; y < height * 7 / 8; ++y) {
        for (int x = width / 2; x < width * 7 / 8; ++x) {
            if ((x - width / 2) + (y - height / 2) < width / 3) {
                img.set(x, y, 240);
            }
        }
    }

    return img;
}

Image create_synthetic_pattern(int width, int height, const std::string& pattern_type) {
    if (pattern_type == "chessboard") {
        return create_chessboard(width, height);
    } else if (pattern_type == "circles") {
        return create_concentric_circles(width, height);
    } else if (pattern_type == "gradient") {
        return create_gradient_ramp(width, height);
    } else {
        return create_geometric_shapes(width, height);
    }
}
